#!/usr/bin/env node
// Generates docs/p16/TOOL_CONTRACT.md from the SG-000065 tool contract.
//   npm run build -w @qdral/mcp && node scripts/generate-tool-contract-doc.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const contract = await import(pathToFileURL(join(repo, "apps", "qdral-mcp", "dist", "tool_contract.js")).href);
const { TOOL_CONTRACT, SURFACE_PROFILES, REMOTE_PROVIDER_PROFILES } = contract;

const yes = (value) => (value ? "yes" : "no");
const names = Object.keys(TOOL_CONTRACT).sort();
const lines = [
  "# Qdral Tool Contract",
  "",
  "Status: CANONICAL CONTRACT FOR QDRAL-P16 (SG-000065). Generated by `scripts/generate-tool-contract-doc.mjs` from",
  "`apps/qdral-mcp/src/tool_contract.ts`; `apps/qdral-mcp/src/tool-contract.test.ts` pins the contract against the tool",
  "sources, MCP discovery on every transport, the OAuth scope matrix, the qdrald remote-session scope table, the parity",
  "inventory, and this document.",
  "",
  "Discovery filtering is never authorization: qdrald, the remote-session lease, and the OAuth ceilings enforce every call.",
  "",
  "## Profiles",
  "",
  "| Profile | Served by | Tools |",
  "| --- | --- | --- |",
  `| \`core\` | relay (remote) | ${SURFACE_PROFILES.core.length} |`,
  `| \`desktop_structured\` | stdio and loopback HTTP (local) | ${SURFACE_PROFILES.desktop_structured.length} |`,
  "",
  "The `developer` and `coordinate_fallback` profiles named in the plan are not mapped and deny. Unknown profiles deny.",
  "",
  "## Providers",
  "",
  "| Remote provider kind | Profile |",
  "| --- | --- |",
  ...Object.entries(REMOTE_PROVIDER_PROFILES).map(([provider, profile]) => `| \`${provider}\` | \`${profile}\` |`),
  "",
  "Every known remote provider shares the `core` ceiling; no provider gains or loses a tool relative to another. Local",
  "transports serve `desktop_structured` regardless of the configured provider kind, which is metadata and never proof of",
  "identity. A remote connection from any other provider kind is refused.",
  "",
  "## Tools",
  "",
  "Annotations: R = readOnlyHint, D = destructiveHint (may delete or overwrite existing user data), I = idempotentHint,",
  "O = openWorldHint (reaches network peers or runs a registered executable).",
  "",
  "| Tool | Kernel shape | Effect | Approval | Remote | R | D | I | O | Output bound |",
  "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ...names.map((name) => {
    const e = TOOL_CONTRACT[name];
    const a = e.annotations;
    const remote = e.remote === "local_only" ? "local-only" : e.remote.join(" ");
    return `| \`${name}\` | \`${e.capability}/${e.operation}\` | ${e.effect} | ${e.approval} | ${remote} | ${yes(a.readOnlyHint)} | ${yes(a.destructiveHint)} | ${yes(a.idempotentHint)} | ${yes(a.openWorldHint)} | ${e.outputBound} |`;
  }),
  ""
];
writeFileSync(join(repo, "docs", "p16", "TOOL_CONTRACT.md"), lines.join("\n"));
console.log("wrote docs/p16/TOOL_CONTRACT.md");
