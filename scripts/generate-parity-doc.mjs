#!/usr/bin/env node
// Generates docs/p16/CAPABILITY_PARITY.md from the SG-000059 inventory.
//   node scripts/generate-parity-doc.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const inventory = JSON.parse(readFileSync(join(repo, "docs", "p16", "capability_parity_inventory.json"), "utf8"));

const counts = (list) =>
  inventory.statuses.map((status) => `${status}: ${list.filter((entry) => entry.status === status).length}`).join(", ");
const detail = (entry) =>
  entry.via?.map((tool) => `\`${tool}\``).join(", ") ?? entry.owner_grain ?? entry.reason ?? entry.mcp_tool ?? "";

const lines = [
  "# Qdral Capability and Parity Inventory",
  "",
  "Status: CANONICAL INVENTORY FOR QDRAL-P16 (SG-000059). Generated by `scripts/generate-parity-doc.mjs` from",
  "`docs/p16/capability_parity_inventory.json`; contract tests in `apps/qdral-mcp/src/parity-inventory.test.ts`",
  "pin both files to the authoritative MCP catalog and the qdrald sources.",
  "",
  "Every intended Desktop Commander-class workflow and every implemented capability is classified exactly once:",
  "`implemented_exposed` (available as an MCP tool), `implemented_hidden` (implemented in qdrald, not yet exposed; the",
  "owning grain exposes it under explicit profiles), `missing` (owning grain implements it), or `intentionally_denied`",
  "(a security decision, not a gap). No MCP surface is widened by this grain.",
  "",
  "## Workflows",
  "",
  `Totals: ${counts(inventory.workflows)}.`,
  "",
  "| Workflow | Status | Tools, owner, or reason |",
  "| --- | --- | --- |",
  ...inventory.workflows.map((w) => `| \`${w.id}\` | ${w.status} | ${detail(w)}${w.note ? ` (${w.note})` : ""} |`),
  "",
  "## Capability shapes",
  "",
  `Totals: ${counts(inventory.capabilities)}.`,
  "",
  "| Shape | Status | MCP tool, owner, or reason |",
  "| --- | --- | --- |",
  ...inventory.capabilities.map((c) => `| \`${c.capability}/${c.operation}\` | ${c.status} | ${c.mcp_tool ? `\`${c.mcp_tool}\`` : detail(c)} |`),
  ""
];
writeFileSync(join(repo, "docs", "p16", "CAPABILITY_PARITY.md"), lines.join("\n"));
console.log("wrote docs/p16/CAPABILITY_PARITY.md");
